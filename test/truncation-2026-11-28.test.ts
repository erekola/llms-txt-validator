import { test } from "node:test";
import assert from "node:assert/strict";
import { validateLlmsTxt, summarizeChecks } from "../src/index.js";

// Regression tests for 0.8.5 (2026-11-28). An outside corpus run found that a file cut at the read
// limit could end inside a list line, and the links check then called that cut line a malformed link
// entry. The last line of a truncated read is now left out of that part of the check. The hosted
// validator carries the same cases in test/validator-truncation-2026-11-28.test.ts in the turva-worker
// repo. The last test pins an answer that was already right: prose before the H1 fails the H1 check.

const read = (text: string, truncated: boolean) => ({ status: 200, contentType: "text/plain; charset=utf-8", text, bytes: Buffer.byteLength(text), truncated });
const byId = (checks: { id: string; status: string; detail: string }[], id: string) => checks.find((c) => c.id === id)!;
// The file a corpus run cut before the closing parenthesis of its last link.
const cut = "# T\n> S\n## D\n- [A](https://example.org)\n- [B](https://example.org/b";

test("0.8.5: the last line of a truncated read is not called a malformed link entry", () => {
  const checks = validateLlmsTxt(read(cut, true));
  const links = byId(checks, "links");
  assert.equal(links.status, "pass", links.detail);
  assert.doesNotMatch(links.detail, /looks like a link entry/);
  assert.equal(byId(checks, "size").status, "warn");
  assert.equal(byId(checks, "size").detail, "over 256 KiB, read truncated");
  assert.equal(summarizeChecks(checks), "valid with warnings");
});

test("0.8.5: the same text without truncation still warns about that line", () => {
  const links = byId(validateLlmsTxt(read(cut, false)), "links");
  assert.equal(links.status, "warn");
  assert.match(links.detail, /1 list line looks like a link entry but is not a Markdown link \(line 5\)/);
});

test("0.8.5: in a truncated read a malformed line before the last one still warns", () => {
  const text = "# T\n> S\n## D\n- [A](https://example.org/a.md: notes)\n- [B](https://example.org/b)\n- [C](https://exam";
  const links = byId(validateLlmsTxt(read(text, true)), "links");
  assert.equal(links.status, "warn");
  assert.match(links.detail, /\(line 4\)$/);
});

test("0.8.5: a truncated read keeps the dash check for every line but the last", () => {
  const EN = String.fromCharCode(0x2013);
  const text = "# T\n> S\n## D\n" + EN + " [A](https://example.org/a)\n- [B](https://example.org/b)\n" + EN + " [C](https://exam";
  const links = byId(validateLlmsTxt(read(text, true)), "links");
  assert.equal(links.status, "warn");
  assert.match(links.detail, /1 list line opens with a dash or bullet that is not a Markdown list marker \(line 4\)/);
});

test("0.8.5: a line of prose before the H1 fails the H1 check", () => {
  const checks = validateLlmsTxt(read("Generated by a plugin.\n\n# T\n\n> S\n\n## D\n\n- [A](https://example.org)\n", false));
  assert.equal(byId(checks, "h1-title").status, "fail");
  assert.equal(summarizeChecks(checks), "not valid");
});
